print("="*50)
print("  PERCEPTRON LEARNING: NOR GATE")
print("  Program by: Samip Khadka")
print("  Roll No: 36")
print("="*50)

# ============================================================
# DATA: NOR Gate (Bipolar: 1 = True, -1 = False)
# NOR = NOT OR
# ============================================================

data = [
    ([1, 1], -1),     # 1 NOR 1 = 0
    ([1, -1], -1),    # 1 NOR 0 = 0
    ([-1, 1], -1),    # 0 NOR 1 = 0
    ([-1, -1], 1)     # 0 NOR 0 = 1
]

print("\nNOR Gate Truth Table:")
print("  x1  x2  |  Target")
print("  ---------------")
for x, t in data:
    print(f"  {x[0]:2}  {x[1]:2}  |    {t:2}")

# ============================================================
# PERCEPTRON NEURON
# ============================================================

w1 = 0.0
w2 = 0.0
bias = 0.0
eta = 1

print("\n" + "="*50)
print("  TRAINING")
print("="*50)
print(f"Initial: w1={w1}, w2={w2}, bias={bias}, η={eta}\n")

# ============================================================
# ACTIVATION FUNCTION
# ============================================================

def activation(x):
    return 1 if x >= 0 else -1

def predict(x1, x2):
    yin = x1*w1 + x2*w2 + bias
    return activation(yin)

# ============================================================
# TRAINING WITH EARLY STOPPING
# ============================================================

for epoch in range(10):
    print(f"Epoch {epoch+1}")
    print("-" * 30)

    correct = 0

    for x, target in data:
        x1, x2 = x
        y = predict(x1, x2)

        # Simplified Perceptron Rule: Update only when wrong
        if y != target:
            w1 = w1 + eta * x1 * target
            w2 = w2 + eta * x2 * target
            bias = bias + eta * target
            dw1 = eta * x1 * target
            dw2 = eta * x2 * target
            db = eta * target
        else:
            dw1 = 0
            dw2 = 0
            db = 0

        if y == target:
            correct += 1

        status = "✅" if y == target else "❌"
        print(f"  ({x1:2}, {x2:2}) → y={y:2}, t={target:2} {status} | Δw=({dw1:4.1f}, {dw2:4.1f}) | w=({w1:4.1f}, {w2:4.1f}) bias={bias:4.1f}")

    print(f"  Accuracy: {correct}/4")

    if correct == 4:
        print(f"\n✅ ALL PATTERNS CORRECT! Stopping at Epoch {epoch+1}")
        break

# ============================================================
# RESULT
# ============================================================

print("\n" + "="*50)
print("  FINAL WEIGHTS")
print("="*50)
print(f"  w1 = {w1:.1f}, w2 = {w2:.1f}, bias = {bias:.1f}")

print("\n" + "="*50)
print("  TESTING")
print("="*50)

print("\n  x1  x2  |  yin  |  y  |  Expected")
print("  " + "-"*30)

for x, target in data:
    x1, x2 = x
    yin = x1*w1 + x2*w2 + bias
    y = activation(yin)
    status = "✅" if y == target else "❌"
    print(f"  {x1:2}  {x2:2}  |  {yin:4.1f}  |  {y:2}  |    {target:2}     {status}")

print("\n" + "="*50)
if y == target:
    print("✅ NOR Gate Learned Successfully!")
    print("   Simplified Perceptron Rule: w = w + η × x × target")
else:
    print("❌ NOR Gate NOT Learned!")
print("="*50)